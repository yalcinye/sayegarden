-- 1) Tablolar ---------------------------------------------------------------

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  latin text,
  price integer not null check (price >= 0),
  size text not null default 'Orta',
  light text,
  water text,
  blurb text,
  badge text,
  categories text[] not null default '{}',
  rating numeric(2,1) not null default 5,
  reviews integer not null default 0,
  sort integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.product_images (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  url text not null,
  path text, -- Storage'daki dosya yolu; dış bağlantılı görsellerde boş
  sort integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists product_images_product_id_idx on public.product_images (product_id, sort);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- 2) Yetki kontrolü ---------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- 3) Satır güvenliği: herkes okur, sadece admin yazar -----------------------

alter table public.products enable row level security;
alter table public.product_images enable row level security;
alter table public.admins enable row level security;

grant select on public.products, public.product_images to anon, authenticated;
grant insert, update, delete on public.products, public.product_images to authenticated;
grant select on public.admins to authenticated;

drop policy if exists "products_public_read" on public.products;
create policy "products_public_read" on public.products
  for select using (active or (select public.is_admin()));

drop policy if exists "products_admin_write" on public.products;
create policy "products_admin_write" on public.products
  for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "images_public_read" on public.product_images;
create policy "images_public_read" on public.product_images
  for select using (
    exists (select 1 from public.products p where p.id = product_id and p.active)
    or (select public.is_admin())
  );

drop policy if exists "images_admin_write" on public.product_images;
create policy "images_admin_write" on public.product_images
  for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "admins_read_self" on public.admins;
create policy "admins_read_self" on public.admins
  for select to authenticated using (user_id = (select auth.uid()));

